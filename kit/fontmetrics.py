def char_width(char):
    """Return the Verdana width ratio for a character, or None if unsupported."""
    if char in _VERDANA:
        return _VERDANA[char]
    if ord(char) > 0x2E80:
        return 1.0
    return None


def text_width(text, size):
    return sum((char_width(ch) or 0.6) * size for ch in str(text))


def has_precise(char):
    return char in _VERDANA
